"""
VCD (Value Change Dump) export.

A VCD file is a header, the declaration of the variables ($scope / $var), the
initial values ($dumpvars) and then the value changes ("#time" + new values).
"""

from datetime import datetime
from typing import TYPE_CHECKING

from flote.simulation.component import Component

if TYPE_CHECKING:
    from ..testbench import WaveSample


def dump(
    component: Component,
    samples: list["WaveSample"],
    end_time: int,
    time_unit: str,
    generator: str,
) -> str:
    """Returns the simulation as the content of a VCD file."""
    buses = component.buses
    symbols = {name: _symbol(i) for i, name in enumerate(buses)}

    # Value of each bus at the start: the first sample, or the current value.
    values = {name: bus.value.get_vcd_repr() for name, bus in buses.items()}
    if samples:
        for signal in samples[0].signals:
            if signal.id in values:
                values[signal.id] = signal.value

    header = (
        f"$version Generated by {generator} $end\n"
        f"$date {datetime.now():%Y-%m-%d %H:%M:%S} $end\n"
        f"$timescale 1 {time_unit} $end\n"
    )
    dumpvars = "".join(_value_line(values[n], symbols[n]) for n in sorted(symbols))

    return (
        header
        + _declarations(component, symbols)
        + "$enddefinitions $end\n"
        + f"$dumpvars\n{dumpvars}$end\n"
        + _changes(samples, end_time, values, symbols)
    )


def _symbol(index: int) -> str:
    """Generates a valid VCD symbol (printable ASCII, base 94) for an index."""
    index, digit = divmod(index, 94)
    symbol = chr(33 + digit)

    while index:
        index, digit = divmod(index, 94)
        symbol = chr(33 + digit) + symbol

    return symbol


def _value_line(value: str, symbol: str) -> str:
    """One value line: scalars have no space ("1!"), vectors are "b<bits> <symbol>"."""
    if len(value) == 1:
        return f"{value}{symbol}\n"

    return f"b{value} {symbol}\n"


def _declarations(component: Component, symbols: dict[str, str]) -> str:
    """
    Declares every bus as a $var. Bus names are dotted paths ("inst.bus"): the
    component is the top $scope and each level of the path is a nested $scope.
    """
    buses = component.buses
    root = component.id_

    lines = [f"$scope module {root} $end"]
    open_scopes = [root]

    # Sorting by scope path (the sort is stable) puts the buses of each scope
    # together, and a scope always comes before the scopes inside it.
    for name in sorted(buses, key=lambda n: n.split(".")[:-1]):
        *path, short_name = name.split(".")
        wanted = [root, *path]

        # Leave the scopes outside the wanted path, then enter the missing ones.
        while open_scopes != wanted[: len(open_scopes)]:
            open_scopes.pop()
            lines.append("\t" * len(open_scopes) + "$upscope $end")
        for scope in wanted[len(open_scopes) :]:
            lines.append("\t" * len(open_scopes) + f"$scope module {scope} $end")
            open_scopes.append(scope)

        bus = buses[name]
        width = len(bus.value.raw_value)
        ref = short_name
        if width > 1:
            first, last = (width - 1, 0) if bus.msb_descending else (0, width - 1)
            ref = f"{short_name}[{first}:{last}]"

        indent = "\t" * len(open_scopes)
        lines.append(f"{indent}$var wire {width} {symbols[name]} {ref} $end")

    for depth in reversed(range(len(open_scopes))):
        lines.append("\t" * depth + "$upscope $end")

    return "\n".join(lines) + "\n"


def _changes(
    samples: list["WaveSample"],
    end_time: int,
    values: dict[str, str],
    symbols: dict[str, str],
) -> str:
    """Writes a "#time" block with the values that changed, for each sample."""
    last_values = dict(values)
    last_time = -1
    datasec = ""

    for sample in samples:
        changes: list[str] = []
        for signal in sample.signals:
            if signal.id in symbols and last_values[signal.id] != signal.value:
                changes.append(_value_line(signal.value, symbols[signal.id]))
                last_values[signal.id] = signal.value

        if changes and sample.time > last_time:
            datasec += f"#{sample.time}\n" + "".join(changes)
            last_time = sample.time

    # Marks the end of the simulation.
    if end_time > last_time:
        datasec += f"#{end_time}\n"

    return datasec
